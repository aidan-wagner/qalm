E2E_SUITE = "S26"
# Row order of the paper's table.
E2E_CIRCUITS = [
    "adder_8",
    "barenco_tof_3",
    "barenco_tof_4",
    "barenco_tof_5",
    "barenco_tof_10",
    "csla_mux_3",
    "csum_mux_9",
    "gf2^4_mult",
    "gf2^5_mult",
    "gf2^6_mult",
    "gf2^7_mult",
    "gf2^8_mult",
    "gf2^9_mult",
    "gf2^10_mult",
    "mod5_4",
    "mod_mult_55",
    "mod_red_21",
    "qcla_adder_10",
    "qcla_com_7",
    "qcla_mod_7",
    "rc_adder_6",
    "tof_3",
    "tof_4",
    "tof_5",
    "tof_10",
    "vbe_adder_3",
]
E2E_CAPTION = (
    r"Comparing \optName with existing optimizers on total gate count reduction "
    r"under a 1-hour time limit, on 26 benchmark circuits used by \quartz. "
    r"The best result for each circuit is in bold."
)
E2E_HEAD = r"""\begin{table*}[ht]
\centering
\caption{%s \vspace{0.5em}}
\label{tab:eval_end_to_end}
\begin{tabular}{l|rrrrrr|r}
\hline
\multicolumn{1}{c|}{\multirow{2}{*}{\textbf{Circuit}}} & \multicolumn{1}{c}{\multirow{2}{*}{\textbf{Orig.}}} & \multicolumn{1}{c}{\multirow{2}{*}{\textbf{\voqc}}} & \multicolumn{1}{c}{\multirow{2}{*}{\textbf{\queso}}} & \multicolumn{1}{c}{\multirow{2}{*}{\textbf{\guoq}}} & \multicolumn{1}{c}{\textbf{\quartz}} & \multicolumn{1}{c|}{\textbf{\quartz}} & \multicolumn{1}{c}{\multirow{2}{*}{\textbf{\optName}}} \\
 &  &  &  &  & \multicolumn{1}{c}{\textbf{w/o Preprocess}} & \multicolumn{1}{c|}{\textbf{w/ Preprocess}} &  \\
\hline"""


def e2e_columns(qalm_config="a"):
    """The 6 optimizer columns of tab:eval_end_to_end, in table order."""
    q_opt, q_params = _qalm(qalm_config)
    return [
        Column("voqc", r"\voqc{}", "voqc", "S26", 3600, {}),
        Column("queso", r"\queso{}", "queso", "S26", 3600, {"opt": "TOTAL"}),
        Column("guoq", r"\guoq{}", "guoq", "S26", 3600, {"opt": "TOTAL"}),
        Column(
            "quartz_nopp", r"\quartz{} w/o preprocessing", "quartz", "S26", 3600, {}
        ),
        Column("quartz_pp", r"\quartz{} w/ preprocessing", "quartz", "S26PP", 3600, {}),
        Column("qalm", r"\optName{}", q_opt, "S26", 3600, q_params),
    ]


def eval_end_to_end_data(rows, qalm_config="a", allow_partial=False):
    """Numbers of tab:eval_end_to_end (unrounded; None where a run is missing).

    Returns {"suite", "n_circuits", "qalm_config", "circuits" (table order),
    "orig": {circuit: S26 total}, "columns": {key: {label, optimizer, suite,
    budget_s, seed, params, n, non_ok, status_counts, opt: {circuit: total or
    None}, geomean_red, n_best}}, "best": {circuit: [column keys]},
    "qalm_vs": {key: {"better", "equal", "worse"}}} where geomean_red is
    metrics.geomean_reduction_pct against the S26 originals and qalm_vs counts
    circuits where QALM's gate count is lower / equal / higher than key's.
    """
    manifest = load_manifest(E2E_SUITE)
    # Every column is joined to the S26 originals by circuit name, so each
    # column's suite (S26PP too) must hold exactly the table circuits.
    for suite in sorted({col.suite for col in e2e_columns(qalm_config)}):
        if sorted(load_manifest(suite)) != sorted(E2E_CIRCUITS):
            raise ValueError(
                f"repro/inputs/{suite}.csv does not hold the 26 table circuits"
            )
    circuits = list(E2E_CIRCUITS)
    orig = {c: manifest[c]["total"] for c in circuits}
    out = {
        "suite": E2E_SUITE,
        "n_circuits": len(circuits),
        "qalm_config": qalm_config,
        "circuits": circuits,
        "orig": orig,
        "columns": {},
    }
    for col in e2e_columns(qalm_config):
        by_circ = select_column(rows, col, allow_partial)
        info = _column_info(col, by_circ)
        info["opt"] = {
            c: by_circ[c]["opt_total"] if c in by_circ else None for c in circuits
        }
        pairs = [(orig[c], by_circ[c]["opt_total"]) for c in circuits if c in by_circ]
        info["geomean_red"] = metrics.geomean_reduction_pct(pairs) if pairs else None
        out["columns"][col.key] = info
    cols = out["columns"]
    out["best"] = {}
    for c in circuits:
        vals = {k: v["opt"][c] for k, v in cols.items() if v["opt"][c] is not None}
        low = min(vals.values()) if vals else None
        out["best"][c] = [k for k, v in vals.items() if v == low]
    for k, v in cols.items():
        v["n_best"] = sum(k in b for b in out["best"].values())
    q = cols["qalm"]["opt"]
    out["qalm_vs"] = {}
    for k, v in cols.items():
        if k == "qalm":
            continue
        both = [c for c in circuits if q[c] is not None and v["opt"][c] is not None]
        out["qalm_vs"][k] = {
            "better": sum(q[c] < v["opt"][c] for c in both),
            "equal": sum(q[c] == v["opt"][c] for c in both),
            "worse": sum(q[c] > v["opt"][c] for c in both),
        }
    return out


def _texttt(circuit):
    return r"\texttt{" + circuit.replace("_", r"\_").replace("^", r"\^{}") + "}"


def render_eval_end_to_end(data):
    cols = data["columns"]
    lines = [AUTOGEN]
    warning = _partial_warning(cols, data["n_circuits"])
    if warning:
        lines.append(warning)
    caption = E2E_CAPTION + _failure_sentence(cols, data["n_circuits"])
    lines += (E2E_HEAD % caption).split("\n")
    for c in data["circuits"]:
        cells = [
            MISSING if v["opt"][c] is None else str(v["opt"][c]) for v in cols.values()
        ]
        cells = _bold_best(cells, min)
        lines.append(" & ".join([_texttt(c), str(data["orig"][c])] + cells) + r" \\")
    geo = [
        MISSING if v["geomean_red"] is None else _fmt(v["geomean_red"], 1) + r"\%"
        for v in cols.values()
    ]
    lines += [
        r"\hline",
        r"\textbf{Geo. Mean Reduction} & " + " & ".join([MISSING] + geo) + r" \\",
        r"\hline",
        r"\end{tabular}",
        r"\end{table*}",
    ]
    return "\n".join(lines) + "\n"


def gen_eval_end_to_end(
    rows,
    out_path=os.path.join(HERE, "out", "eval_end_to_end.tex"),
    qalm_config="a",
    allow_partial=False,
):
    """Write eval_end_to_end.tex; return the dict of eval_end_to_end_data."""
    data = eval_end_to_end_data(rows, qalm_config, allow_partial)
    _write(render_eval_end_to_end(data), out_path)
    return data


