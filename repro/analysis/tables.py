# Table tab:avg-comparison (248 circuits)
# ---------------------------------------------------------------------------

AVG_SUITE = "S248"
AVG_METRICS = [  # (key in metrics.averages, row label, decimals)
    ("fidelity", "Fidelity", 4),
    ("cx_red", r"2Q Gate Reduction (\%)", 2),
    ("total_red", r"Total Gate Reduction (\%)", 2),
]
AVG_CAPTION = (
    "Per-metric averages across the benchmark suite. Each optimizer is given one "
    "hour per circuit, except for ``\\optName{} (1 minute)'', which is given only "
    "one minute per circuit."
)
AVG_HEAD = r"""% Averages of the dashed reference lines in the 3xN comparison figure.
\begin{table*}[t]
  \centering
%  \small
  \setlength{\tabcolsep}{4pt}
  \begin{tabular}{l c c c c c c c c }
    \toprule
%    Metric & QALM & GUOQ (2Q Gate) & GUOQ (Total Gate) & QUESO (2Q
%    Gate) & QUESO (Total Gate) & VOQC & Quartz \\
\multirow{2}{*}{Metric} & \multirow{2}{*}{QALM} & QALM & GUOQ & GUOQ & QUESO & QUESO & \multirow{2}{*}{VOQC} & \multirow{2}{*}{Quartz} \\
& & (1 minute) & (2Q Gate) & (Total Gate) & (2Q Gate) & (Total Gate) & & \\
    \midrule"""


def averages_columns(qalm_config="a"):
    """The 8 columns of tab:avg-comparison, in table order."""
    q_opt, q_params = _qalm(qalm_config)
    s = AVG_SUITE
    return [
        Column("qalm", r"\optName{}", q_opt, s, 3600, q_params),
        Column("qalm_1min", r"\optName{} (1 minute)", q_opt, s, 60, q_params),
        Column("guoq_2q", r"\guoq{} (2Q Gate)", "guoq", s, 3600, {"opt": "TWO_Q"}),
        Column(
            "guoq_total", r"\guoq{} (Total Gate)", "guoq", s, 3600, {"opt": "TOTAL"}
        ),
        Column("queso_2q", r"\queso{} (2Q Gate)", "queso", s, 3600, {"opt": "TWO_Q"}),
        Column(
            "queso_total", r"\queso{} (Total Gate)", "queso", s, 3600, {"opt": "TOTAL"}
        ),
        Column("voqc", r"\voqc{}", "voqc", s, 3600, {}),
        Column("quartz", r"\quartz{}", "quartz", s, 3600, {}),
    ]


def averages_table_data(rows, qalm_config="a", allow_partial=False):
    """Numbers of tab:avg-comparison (unrounded; None for a column without rows).

    Returns {"suite", "n_circuits", "qalm_config", "columns": {key: {label,
    optimizer, suite, budget_s, seed, params, n, non_ok, status_counts,
    fidelity, cx_red, total_red}}}, columns in table order.
    """
    out = {
        "suite": AVG_SUITE,
        "n_circuits": len(load_manifest(AVG_SUITE)),
        "qalm_config": qalm_config,
        "columns": {},
    }
    for col in averages_columns(qalm_config):
        by_circ = select_column(rows, col, allow_partial)
        info = _column_info(col, by_circ)
        avg = metrics.averages([by_circ[c] for c in sorted(by_circ)]) if by_circ else {}
        for key, _, _ in AVG_METRICS:
            info[key] = avg.get(key)
        out["columns"][col.key] = info
    return out


def render_averages_table(data):
    cols = data["columns"]
    lines = [AUTOGEN]
    warning = _partial_warning(cols, data["n_circuits"])
    if warning:
        lines.append(warning)
    lines += AVG_HEAD.split("\n")
    for key, label, digits in AVG_METRICS:
        cells = _bold_best([_fmt(c[key], digits) for c in cols.values()], max)
        lines.append(f"    {label:<27}& " + " & ".join(cells[:5]) + " &")
        lines.append("    " + " & ".join(cells[5:]) + r" \\")
    caption = AVG_CAPTION + _failure_sentence(cols, data["n_circuits"])
    lines += [
        r"    \bottomrule",
        r"  \end{tabular}",
        r"  \caption{" + caption + "}",
        r"  \label{tab:avg-comparison}",
        r"\end{table*}",
        "",
    ]
    return "\n".join(lines) + "\n"


def gen_averages_table(
    rows,
    qalm_config="a",
    out_path=os.path.join(HERE, "out", "averages_table.tex"),
    allow_partial=False,
):
    """Write averages_table.tex; return the dict of averages_table_data."""
    data = averages_table_data(rows, qalm_config, allow_partial)
    _write(render_averages_table(data), out_path)
    return data


