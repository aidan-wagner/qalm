def _summary(avg, e2e):
    """Human-readable summary of both tables (printed by the CLI)."""
    lines = [f"tab:avg-comparison (QALM config {avg['qalm_config']}, {AVG_SUITE})"]
    for k, c in avg["columns"].items():
        nums = " / ".join(_fmt(c[m], d + 2) for m, _, d in AVG_METRICS)
        lines.append(
            f"  {k:<12} n={c['n']:<3} fid/cx_red/total_red = {nums}"
            f"  non_ok={c['non_ok']} {c['status_counts'] or ''}"
        )
    lines.append(
        f"tab:eval_end_to_end (QALM config {e2e['qalm_config']}, S26 originals)"
    )
    for k, c in e2e["columns"].items():
        lines.append(
            f"  {k:<12} n={c['n']:<3} geomean_red={_fmt(c['geomean_red'], 3)}"
            f"  n_best={c['n_best']}  non_ok={c['non_ok']} {c['status_counts'] or ''}"
        )
    for k, v in e2e["qalm_vs"].items():
        lines.append(
            f"  qalm vs {k:<12} better/equal/worse = {v['better']}/{v['equal']}/{v['worse']}"
        )
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "--results", default=os.path.join(REPRO, "results"), help="dir with runs.csv"
    )
    ap.add_argument("--out", default=os.path.join(HERE, "out"), help="output directory")
    ap.add_argument("--qalm-config", choices=sorted(QALM_CONFIGS), default="a")
    ap.add_argument(
        "--allow-partial", action="store_true", help="render partially covered columns"
    )
    args = ap.parse_args()
    rows = metrics.load_runs(args.results)
    source = os.path.join(args.results, "runs.csv")
    print(f"{len(rows)} rows from {source}")
    kw = {"qalm_config": args.qalm_config, "allow_partial": args.allow_partial}
    avg_path = os.path.join(args.out, "averages_table.tex")
    e2e_path = os.path.join(args.out, "eval_end_to_end.tex")
    avg = gen_averages_table(rows, out_path=avg_path, **kw)
    e2e = gen_eval_end_to_end(rows, out_path=e2e_path, **kw)
    print(_summary(avg, e2e))
    print(f"wrote {avg_path}\nwrote {e2e_path}")


if __name__ == "__main__":
    main()
