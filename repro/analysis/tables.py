"""Generate the paper's two result tables (LaTeX) from result rows.

Inputs
    Result rows in the ``metrics.load_runs`` schema: by default
    ``<results>/runs.csv`` written by ``repro/harness/run.py collect``.
    The input manifests ``repro/inputs/{S248,S26,S26PP}.csv`` define the
    circuit set of each suite and its original gate counts.

Outputs (written to ``--out``, default ``repro/analysis/out``)
    averages_table.tex   the paper's figtex/averages_table.tex
                         (Table tab:avg-comparison, 248-circuit averages).
    eval_end_to_end.tex  the paper's figtex/eval_end_to_end.tex
                         (Table tab:eval_end_to_end, 26 circuits of Quartz).

Both files have the layout of the paper's tables; an optional caption sentence
lists failed runs.
``averages_table_data`` and ``eval_end_to_end_data`` return the numbers used
(unrounded) as plain dicts, for numbers.tex.

Selection rules (see repro/README.md):
    * QALM is configuration "a" (optimizer ``qalm`` with greedy_k=2, n_pool=1,
      n_branch=3, fixed_k=0, enqueue=0) or "b" (optimizer ``qalm_old``);
      "QALM (1 minute)" is the same configuration with a 60 s budget.
      Every other column has a 3600 s budget; all columns use seed 0.
    * Every column must hold exactly one row per circuit of its suite.  A
      column without any row is rendered as "--"; a partially covered column
      is an error unless ``allow_partial`` is set (then the tex file gets a
      WARNING comment and the numbers cover only the circuits present).
    * Failed runs already count as the best circuit reported within the
      budget, or the original circuit (repro/harness/collect.py).  Each
      caption names, per column, the runs whose status is not OK.
    * The 26-circuit table compares against the S26 (nam_circs) original
      counts in every column, including Quartz w/ preprocessing, whose inputs
      (S26PP, rotation-merged) are smaller.

All metrics come from metrics.py.  Bold marks the best displayed value per
row (highest for the averages table, lowest gate count incl. ties for the
26-circuit table); "--" cells and the Orig. column never count.

CLI (from the repo root):
    uv run repro/analysis/tables.py --results repro/results \
        --out repro/analysis/out [--qalm-config a|b] [--allow-partial]
"""

import argparse
import csv
import os
import sys
from collections import Counter, namedtuple

HERE = os.path.dirname(os.path.abspath(__file__))
REPRO = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import metrics  # noqa: E402

AUTOGEN = "% Auto-generated by repro/analysis/tables.py — do not edit by hand."
MISSING = "--"
SEED = 0  # canonical runs
QALM_CONFIGS = {
    "a": (
        "qalm",
        {
            "greedy_k": 2,
            "n_pool": 1,
            "n_branch": 3,
            "fixed_k": 0,
            "enqueue": 0,
        },
    ),
    "b": ("qalm_old", {}),
}

# One table column: which rows it averages and how the caption names it.
Column = namedtuple("Column", "key label optimizer suite budget_s params")


def _qalm(qalm_config):
    if qalm_config not in QALM_CONFIGS:
        raise ValueError(f"qalm_config must be one of {sorted(QALM_CONFIGS)}")
    return QALM_CONFIGS[qalm_config]


def load_manifest(suite):
    """{circuit: {"sha256", "total", "cx"}} of repro/inputs/<suite>.csv, in file order."""
    with open(os.path.join(REPRO, "inputs", f"{suite}.csv")) as f:
        return {
            r["name"]: {
                "sha256": r["sha256"],
                "total": int(r["total"]),
                "cx": int(r["cx"]),
            }
            for r in csv.DictReader(f)
        }


def select_column(rows, col, allow_partial=False):
    """{circuit: row} of one column, checked against the suite manifest."""
    manifest = load_manifest(col.suite)
    sel = metrics.select(
        rows,
        col.optimizer,
        suite=col.suite,
        budget_s=col.budget_s,
        seed=SEED,
        **col.params,
    )
    by_circ = {}
    for r in sel:
        c = r["circuit"]
        where = f"column {col.key}, circuit {c}"
        if c in by_circ:
            raise ValueError(
                f"{where}: two rows ({by_circ[c]['job_id']}, {r['job_id']})"
            )
        if c not in manifest:
            raise ValueError(f"{where}: not in suite {col.suite}")
        if r["status"] == "INFRA":
            raise ValueError(f"{where}: status INFRA (must be re-run, never reported)")
        m = manifest[c]
        got = (r["input_sha256"], r["orig_total"], r["orig_cx"])
        if got != (m["sha256"], m["total"], m["cx"]):
            raise ValueError(
                f"{where}: input {got} differs from the {col.suite} manifest"
            )
        by_circ[c] = r
    missing = [c for c in manifest if c not in by_circ]
    if by_circ and missing and not allow_partial:
        raise ValueError(
            f"column {col.key}: {len(missing)} of {len(manifest)} circuits have no row "
            f"(e.g. {missing[:3]}); use allow_partial to render the others"
        )
    return by_circ


def _column_info(col, by_circ):
    status = Counter(r["status"] for r in by_circ.values() if r["status"] != "OK")
    return {
        "label": col.label,
        "optimizer": col.optimizer,
        "suite": col.suite,
        "budget_s": col.budget_s,
        "seed": SEED,
        "params": dict(col.params),
        "n": len(by_circ),
        "non_ok": sum(status.values()),
        "status_counts": dict(sorted(status.items())),
    }


def _fmt(value, digits):
    """Fixed-point string, "--" for None, never "-0.00"."""
    if value is None:
        return MISSING
    s = f"{value:.{digits}f}"
    return f"{0:.{digits}f}" if float(s) == 0 else s


def _bold_best(cells, best):
    """Bold every displayed value equal to best(displayed values); "--" never counts."""
    shown = [float(s) for s in cells if s != MISSING]
    if not shown:
        return list(cells)
    b = best(shown)
    return [rf"\textbf{{{s}}}" if s != MISSING and float(s) == b else s for s in cells]


def _join_and(parts):
    if len(parts) <= 2:
        return " and ".join(parts)
    return ", ".join(parts[:-1]) + ", and " + parts[-1]


def _failure_sentence(columns, n_circuits):
    """Caption sentence naming, per column, the runs with status != OK ("" if none)."""
    parts = [f"{c['non_ok']} for {c['label']}" for c in columns.values() if c["non_ok"]]
    if not parts:
        return ""
    parts[0] = parts[0].replace(" for ", f" of {n_circuits} for ", 1)
    return (
        f" The runs that did not finish normally ({_join_and(parts)}) are counted "
        "with the best circuit reported within the time limit, or with the "
        "original circuit if none was reported."
    )


def _partial_warning(columns, n_circuits):
    """Tex comment line flagging partially covered columns (None if all complete)."""
    partial = [f"{k} n={c['n']}" for k, c in columns.items() if 0 < c["n"] < n_circuits]
    if not partial:
        return None
    return f"% WARNING: partial data (of {n_circuits} circuits): " + ", ".join(partial)


def _write(text, out_path):
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(text)


